List<BusModel> getBusesByRoute(String from, String to) {
  final result = getMockBuses()
      .where(
        (b) =>
            b.from.toLowerCase().trim() == from.toLowerCase().trim() &&
            b.to.toLowerCase().trim() == to.toLowerCase().trim(),
      )
      .toList();
  result.sort((a, b) => a.price.compareTo(b.price));
  return result;
}

int getCheapestPriceForRoute(String from, String to, int dayOffset) {
  final buses = getBusesByRoute(from, to);
  if (buses.isEmpty) return 0;

  int basePrice = 999999;
  for (final bus in buses) {
    final cheapPlatform = bus.platforms.values.reduce((a, b) => a < b ? a : b);
    if (cheapPlatform < basePrice) {
      basePrice = cheapPlatform;
    }
  }

  const variations = [55, 30, 0, 20, 35, 55, 80];
  return basePrice + variations[dayOffset.clamp(0, 6)];
}
